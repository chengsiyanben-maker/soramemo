-- 図鑑の索引のための「名前の読み」（11/9 本人が決めた図鑑の形。PM の指示 11/9 22時50分）
--   86空港と番外編（自衛隊の飛行場・滑空場・飛行場・一般の人が行けない飛行場）の全部、public.airports の全行に1行ずつ。
--   使い道：図鑑の索引の50音順（index_yomi）と、探す欄で読みでも当てる（yomi・index_yomi・alt_yomi）。
--   yomi      … 正式な名前の読み（例：東京国際空港（羽田）→ とうきょうこくさいくうこう）
--   index_yomi… 索引で並べる・頭の字に使う読み。ふだん呼ぶ名前で「空港・基地・滑空場」などは付けない（例：はねだ）
--   alt_yomi  … 探す欄で当てる別の読み（通称・愛称の読み。例：こまき→なごや、ちゅうぶ→せんとれあ）。公式キャラの名前を含む愛称は入れない
--   source    … 'official'＝公的な一覧に載っている読み（source_ref に出典）／'manual'＝手で付けた読み。
--               国土交通省の空港一覧・国土数値情報の空港データには読みの欄がないので、今は全部 manual
-- 読むのは誰でも（図鑑はログイン前のデモでも見る）。書くのは運営（service_role）だけ。
-- 影響：チェックイン（図鑑の索引・探す欄）だけ。エアライン経営は使わない。public.airports は変えない。

create table if not exists public.airport_yomi (
  airport_id integer primary key references public.airports(id) on delete cascade,
  yomi       text    not null check (yomi ~ '^[ぁ-ゖー]+$' and char_length(yomi) <= 60),
  index_yomi text    not null check (index_yomi ~ '^[ぁ-ゖー]+$' and char_length(index_yomi) <= 30),
  alt_yomi   text[]  not null default '{}' check (cardinality(alt_yomi) <= 5 and array_to_string(alt_yomi, '') ~ '^[ぁ-ゖー]*$' and array_position(alt_yomi, null) is null),
  source     text    not null default 'manual' check (source in ('official', 'manual')),
  source_ref text    check (source_ref is null or char_length(source_ref) <= 300),
  updated_at timestamptz not null default now(),
  constraint airport_yomi_official_ref check (source = 'manual' or source_ref is not null)
);
comment on table public.airport_yomi is '図鑑の索引の名前の読み（ひらがな）。airports の全行に1行。source=manual は手で付けた読み';

-- 直したら updated_at を今に
create or replace function public.airport_yomi_touch() returns trigger language plpgsql set search_path = '' as $$
begin new.updated_at := now(); return new; end $$;
drop trigger if exists airport_yomi_touch on public.airport_yomi;
create trigger airport_yomi_touch before update on public.airport_yomi for each row execute function public.airport_yomi_touch();

