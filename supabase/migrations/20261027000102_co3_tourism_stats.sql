insert into public.co3_tourism (iata, degree)
select distinct on (a.iata) a.iata, least(1.5, p.degree + case when co3.is_island(a.iata) then 0.2 else 0 end)
  from public.airports a join p on p.pref = a.prefecture
 where a.iata ~ '^[A-Z]{3}$'
 order by a.iata
on conflict (iata) do update set degree = excluded.degree;
