// 試遊版のチート（play.sql）が効くかを確かめる：node tools/play/cheat_test.mjs
import { buildDb, UID } from './seed.mjs';
const db = await buildDb();
const as = async (sql) => { await db.exec(`set role authenticated; select set_config('request.jwt.claim.sub','${UID}',false);`); try { return Object.values((await db.query(sql)).rows[0] ?? {})[0]; } finally { await db.exec('reset role'); } };
let bad = 0; const ok = (l, c, v) => { console.log((c ? 'OK ' : 'NG ') + l, c ? '' : JSON.stringify(v)); if (!c) bad++; };
let s = await as('select public.co_state()');
const r0 = s.routes.length;
await db.query(`select play.set_company($1, 3, 77, 100000)`, [UID]);
await db.query(`select play.set_company($1, null, null, 10)`, [UID]);
s = await as('select public.co_state()');
ok('格付け・満足度・資金', s.rating === 3 && Math.round(s.satisfaction) === 77 && s.cash >= 100000, { r: s.rating, sat: s.satisfaction, cash: s.cash });
const reg = (await db.query(`select play.add_flight($1, 'HND', 'ISG', 'B789') v`, [UID])).rows[0].v;
s = await as('select public.co_state()');
const h = await as('select public.co_hangar()');
ok('乗ったことにする：路線が増えて、その機体が買える', s.routes.length === r0 + 1 && h.some((x) => x.reg === reg && x.icao === 'B789'), { r: s.routes.length, reg });
await db.query(`select play.add_seen($1, 'NRT', array['A388','B77W']) v`, [UID]);
const seen = await as('select public.co3_seen_list()');
ok('見たにする：成田で A380・777-300ER', seen.some((x) => x.code === 'A388') && seen.some((x) => x.code === 'B77W'), seen.slice(0, 3));
await db.query(`select play.typhoon('CTS')`);
ok('台風', Number((await db.query(`select count(*) n from co3_typhoon_fcst where iata = 'CTS' and day = co3.today() + 1`)).rows[0].n) === 1, null);
await db.query(`select play.weather('CTS', 'snow')`);
ok('雪', Number((await db.query(`select count(*) n from co3_wx where iata = 'CTS' and snow`)).rows[0].n) === 24, null);
const n = (await db.query(`select play.cancel('HND', 'CTS', 0.5) v`)).rows[0].v;
ok('欠航（羽田⇄新千歳の半分くらい）', n > 10 && n < 40, n);
await db.query(`select play.set_season('2026-12-30')`);
ok('季節：年末年始', (await db.query(`select co3.today()::text d`)).rows[0].d === '2026-12-30' && (await as('select public.co_state()')).season.name.includes('年末'), (await as('select public.co_state()')).season);
await db.query(`select play.advance(1)`);
ok('季節：1日進めると12/31', (await db.query(`select co3.today()::text d`)).rows[0].d === '2026-12-31', null);
await db.query(`select play.set_season(null)`);
ok('季節：今日に戻す', (await db.query(`select co3.today() = (now() at time zone 'Asia/Tokyo')::date v`)).rows[0].v === true, null);
console.log(bad ? 'NG ' + bad : 'ALL OK'); process.exit(bad ? 1 : 0);
