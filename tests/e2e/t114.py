async def page(b, init='', onboarded=True, shots=False):
    c = await b.new_context(viewport={'width':390,'height':844}, device_scale_factor=2 if shots else 1, geolocation={'latitude':35.55,'longitude':139.78,'accuracy':20}, permissions=['geolocation'])
    await c.route('https://cdn.jsdelivr.net/npm/@supabase/**', lambda r: r.fulfill(path=os.path.join(HERE,'fake_sb.js'), content_type='application/javascript'))
    await c.add_init_script(("localStorage.setItem('soramemo.onboarded','1');" if onboarded else "") + init)
    pg = await c.new_page(); errs = []; pg.on('pageerror', lambda e: errs.append(str(e)))
    await pg.goto('file://'+os.path.join(WORK,'index_server_test.html')); await pg.wait_for_load_state('load')
    await pg.wait_for_function('document.readyState === "complete" && typeof render === "function" && typeof sb !== "undefined" && !!sb'); await pg.wait_for_timeout(500)
    return c, pg, errs
