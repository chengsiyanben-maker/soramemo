// 行事のボーナス：期間中のチェックインで空港ごとに1回、珍しい空港は倍、経営の「受け取る」で資金に入る
import { PGlite } from '@electric-sql/pglite';
import fs from 'fs';
const db = new PGlite(); const dir = new URL('../../supabase/migrations/', import.meta.url).pathname;
await db.exec(`create role anon nologin; create role authenticated nologin; create role service_role nologin; create schema auth;
create table auth.users (id uuid primary key, email text, created_at timestamptz default now());
create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
create function auth.jwt() returns jsonb language sql stable as $$ select jsonb_build_object('sub', current_setting('request.jwt.claim.sub', true), 'aal', 'aal2') $$;
grant usage on schema public, auth to anon, authenticated, service_role; grant execute on function auth.uid(), auth.jwt() to anon, authenticated, service_role;`);
for (const f of fs.readdirSync(dir).sort()) await db.exec(fs.readFileSync(dir + f, 'utf8'));
const as = async (role, sql) => { try { await db.exec(`set role ${role}`); const r = await db.query(sql); return r.rows.length ? Object.values(r.rows[0])[0] : 'ok'; } catch (e) { return 'ERROR: ' + e.message.split('\n')[0]; } finally { await db.exec('reset role'); } };
let bad = 0; const check = (label, ok, v) => { console.log((ok ? 'OK ' : 'NG ') + label, ok ? '' : JSON.stringify(v)); if (!ok) bad++; };
const U = '00000000-0000-0000-0000-0000000000e1';
await db.exec(`insert into auth.users (id) values ('${U}');
  insert into public.game_events (id, name, starts_at, ends_at, bonus) values ('test-now', 'テスト', now() - interval '1 day', now() + interval '1 day', 5000), ('test-old', '昔', now() - interval '10 days', now() - interval '5 days', 9999)`);
const ap = (await db.query(`select (select id from public.airports where not rare and game_target order by id limit 1) as n, (select id from public.airports where rare and game_target order by id limit 1) as r`)).rows[0];
let r = await as('anon', `select public.current_events()`);
check('いま開いている行事が見える（終わった行事は出ない）', r?.some?.((e) => e.id === 'test-now' && e.open) && !r.some((e) => e.id === 'test-old'), r);
check('最初の行事（年末年始）は入っている', (await db.query(`select count(*)::int as n from public.game_events where id = 'newyear-2027'`)).rows[0].n === 1, null);
r = await as('anon', `select public.grant_event_bonus('${U}', ${ap.n}, now())`);
check('ボーナスを作る関数は、匿名では呼べない', String(r).startsWith('ERROR'), r);
r = (await db.query(`select public.grant_event_bonus('${U}', ${ap.n}, now()) as x`)).rows[0].x;
check('期間中のチェックインでボーナス', r.length === 1 && r[0].amount === 5000 && r[0].name === 'テスト', r);
r = (await db.query(`select public.grant_event_bonus('${U}', ${ap.n}, now()) as x`)).rows[0].x;
check('同じ空港は1回だけ', r.length === 0, r);
r = (await db.query(`select public.grant_event_bonus('${U}', ${ap.r}, now()) as x`)).rows[0].x;
check('珍しい空港は2倍', r.length === 1 && r[0].amount === 10000, r);
r = (await db.query(`select public.grant_event_bonus('${U}', ${ap.n}, now() - interval '7 days') as x`)).rows[0].x;
check('行事ごとに数える（昔の行事の期間の時刻なら、その行事のボーナス）', r.length === 1 && r[0].event === 'test-old', r);
await db.exec(`set request.jwt.claim.sub = '${U}'`);
r = await as('authenticated', `select public.my_event_bonus()`);
check('まだ受け取っていない合計', Number(r?.pending) === 24999, r);
await db.exec(`update ops.flags set value = 'true' where key = 'game_released'`);
r = await as('authenticated', `select public.co_collect()`);
check('受け取ると資金に入る', Number(r?.cash) >= 24999, r?.cash ?? r);
r = await as('authenticated', `select public.my_event_bonus()`);
check('受け取ったあとは残りが0', Number(r?.pending) === 0 && Number(r.total) === 24999, r);
r = await as('authenticated', `select public.admin_set_event('x-test', 'x', now(), now() + interval '1 day', 1)`);
check('行事を足すのは運営者だけ', String(r).startsWith('ERROR'), r);
if (bad) process.exit(1);
