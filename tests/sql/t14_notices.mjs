// 空港ごとのお知らせ：利用者は掲載中のものだけ読める・運営者だけが書ける・出典URLは https のみ
import { PGlite } from '@electric-sql/pglite';
import fs from 'fs';
const db = new PGlite(); const dir = new URL('../../supabase/migrations/', import.meta.url).pathname;
await db.exec(`create role anon nologin; create role authenticated nologin; create role service_role nologin; create schema auth;
create table auth.users (id uuid primary key, email text, created_at timestamptz default now());
create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid $$;
create function auth.jwt() returns jsonb language sql stable as $$ select jsonb_build_object('sub', current_setting('request.jwt.claim.sub', true), 'aal', 'aal2') $$;
grant usage on schema public, auth to anon, authenticated, service_role; grant execute on function auth.uid(), auth.jwt() to anon, authenticated, service_role;`);
for (const f of fs.readdirSync(dir).sort()) await db.exec(fs.readFileSync(dir + f, 'utf8'));
await db.exec(`set co3.season_day = '2026-05-20'`);   // 季節の需要のない日で手計算する（季節は t72）
const ADM = 'aaaaaaaa-aaaa-aaaa-aaaa-aaaaaaaaaaaa', U = '11111111-1111-1111-1111-111111111111';
await db.exec(`insert into auth.users (id) values ('${ADM}'),('${U}'); insert into ops.admins values ('${ADM}');`);
const as = async (role, uid, sql) => { try { await db.exec(`set role ${role}; select set_config('request.jwt.claim.sub','${uid}',false);`); const r = await db.query(sql); return r.rows.length ? Object.values(r.rows[0])[0] : 'ok'; } catch (e) { return 'ERROR: ' + e.message.split('\n')[0]; } finally { await db.exec('reset role'); } };
let bad = 0; const check = (label, ok, v) => { console.log((ok ? 'OK ' : 'NG ') + label, ok ? '' : JSON.stringify(v)); if (!ok) bad++; };
const save = (uid, url, exp = 'null', pub = `'2026-10-01'`) => as('authenticated', uid, `select public.admin_save_notice(null, 1, '第2ターミナルの工事', '一部の通路が通れません', '成田国際空港', '${url}', ${pub}, ${exp})`);
let r = await save(U, 'https://www.narita-airport.jp/');
check('利用者は書けない', String(r).startsWith('ERROR'), r);
r = await as('anon', '', `select count(*) from ops.airport_notices`);
check('表は直接読めない', String(r).startsWith('ERROR'), r);
const id = await save(ADM, 'https://www.narita-airport.jp/');
check('運営者は書ける', typeof id === 'number' || /^\d+$/.test(String(id)), id);
r = await save(ADM, 'http://example.com/');
check('http は断る', String(r).startsWith('ERROR'), r);
r = await save(ADM, 'javascript:alert(1)');
check('javascript: は断る', String(r).startsWith('ERROR'), r);
await save(ADM, 'https://www.narita-airport.jp/old', `'2026-01-02'`, `'2026-01-01'`);
r = await as('anon', '', 'select public.airport_notices()');
check('未ログインでも掲載中の1件だけ読める', Array.isArray(r) && r.length === 1 && r[0].source_name === '成田国際空港', r);
r = await as('authenticated', U, `select public.admin_set_notice_active(${id}, false)`);
check('利用者は取り下げられない', String(r).startsWith('ERROR'), r);
await as('authenticated', ADM, `select public.admin_set_notice_active(${id}, false)`);
r = await as('anon', '', 'select public.airport_notices()');
check('取り下げると見えない', Array.isArray(r) && r.length === 0, r);
r = await as('authenticated', ADM, 'select public.admin_notices()');
check('運営者は全件見える', Array.isArray(r) && r.length === 2, r);
r = (await db.query(`select count(*)::int n from ops.admin_actions where action like 'notice_%'`)).rows[0].n;
check('操作が記録に残る', Number(r) === 3, r);
if (bad) process.exit(1);
